import numpy as np
import pandas as pd

# ============================================================
# ЗАДАЧА 2: Метод парных сравнений (Матрица Саати)
# ============================================================
print("=" * 70)
print("ЗАДАЧА 2: Метод парных сравнений")
print("Тема: Важность характеристик при выборе кофейни")
print("=" * 70)

# Матрица парных сравнений (обратно симметричная, a_ij = 1 / a_ji)
# Составлена так, чтобы быть близкой к согласованной (CR < 0.1)
A = np.array([
    [1,   2,   2,   4,   4,   6],   # Цена
    [1/2, 1,   2,   3,   3,   5],   # Вкус
    [1/2, 1/2, 1,   2,   2,   4],   # Атмосфера
    [1/4, 1/3, 1/2, 1,   1,   2],   # Скорость обслуживания
    [1/4, 1/3, 1/2, 1,   1,   2],   # Локация
    [1/6, 1/5, 1/4, 1/2, 1/2, 1]    # Наличие Wi-Fi
])

n = A.shape[0]
labels = ['Цена', 'Вкус', 'Атмосфера', 'Скорость', 'Локация', 'Wi-Fi']

print("\n1. Матрица парных сравнений A:")
print(pd.DataFrame(A, index=labels, columns=labels).round(4))

# 2. Собственные числа и векторы
eigenvalues, eigenvectors = np.linalg.eig(A)

# Максимальное собственное число (действительное)
lambda_max = max(eigenvalues.real)
print(f"\n2. Максимальное собственное число λ_max = {lambda_max:.4f}")

# 3. Собственный вектор для λ_max
idx_max = np.argmax(eigenvalues.real)
w_raw = eigenvectors[:, idx_max].real

# Убираем возможный знак минус (собственный вектор определен с точностью до знака)
if w_raw.sum() < 0:
    w_raw = -w_raw

# ЭТАП 1: Нормализация на сумму (сумма = 1, как вероятности)
W_sum = w_raw / w_raw.sum()

# ЭТАП 2: Нормализация на максимум (max = 1)
# Как в методичке: "Нечеткое множество получилось субнормальным. 
# Для нормализации разделим все степени принадлежности на максимальное значение"
max_val = W_sum.max()
W_max = W_sum / max_val

print("\n3. Степени принадлежности (собственный вектор):")
df_weights = pd.DataFrame({
    'Характеристика': labels,
    'W (исходный)': w_raw.round(4),
    'μ (норм. на сумму)': W_sum.round(4),
    'μ (норм. на макс)': W_max.round(4)
})
print(df_weights)

print(f"\n   💡 Примечание: Максимальное значение при нормировке на сумму равно {max_val:.4f}.")
print(f"   Множество субнормально. Для нормализации мы разделили все значения на {max_val:.4f},")
print(f"   чтобы максимальная степень принадлежности стала равна 1.0 (как в методичке).")

# 4. Мера согласованности
CI = (lambda_max - n) / (n - 1)
RI_table = {1: 0, 2: 0, 3: 0.58, 4: 0.90, 5: 1.12, 6: 1.24, 7: 1.32, 8: 1.41, 9: 1.45, 10: 1.49}
RI = RI_table.get(n, 1.24)
CR = CI / RI if RI > 0 else 0

print("\n4. Оценка согласованности суждений эксперта:")
print(f"   Индекс согласованности (CI) = (λ_max − n) / (n − 1) = {CI:.4f}")
print(f"   Случайный индекс (RI) для n={n} = {RI}")
print(f"   Отношение согласованности (CR) = CI / RI = {CR:.4f}")

if CR < 0.1:
    print("   ✅ CR < 0.1 → Матрица СОГЛАСОВАНА (суждения эксперта логичны)")
elif CR < 0.2:
    print("   ⚠️ 0.1 ≤ CR < 0.2 → Допустимо, но есть небольшая несогласованность")
else:
    print("   ❌ CR ≥ 0.2 → Матрица НЕСОГЛАСОВАНА, нужно пересмотреть оценки")