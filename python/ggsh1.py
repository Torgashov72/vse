import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# ============================================================
# ЗАДАЧА 1: Метод статистической обработки экспертной информации
# ============================================================
print("=" * 70)
print("ЗАДАЧА 1: Статистическая обработка мнений экспертов")
print("Тема: Уровень освещенности рабочего места (в люксах)")
print("=" * 70)

# 6 диапазонов освещенности
ranges = ['100-200', '200-300', '300-400', '400-500', '500-600', '600-700']
terms = ['Тусклый', 'Комфортный', 'Яркий']

# Данные опроса 5 экспертов (1 - наличие свойства, 0 - отсутствие)
experts = {
    'Эксперт 1': {
        'Тусклый':    [1, 1, 0, 0, 0, 0],
        'Комфортный': [0, 1, 1, 1, 0, 0],
        'Яркий':      [0, 0, 0, 1, 1, 1]
    },
    'Эксперт 2': {
        'Тусклый':    [1, 1, 1, 0, 0, 0],
        'Комфортный': [0, 0, 1, 1, 1, 0],
        'Яркий':      [0, 0, 0, 0, 1, 1]
    },
    'Эксперт 3': {
        'Тусклый':    [1, 0, 0, 0, 0, 0],
        'Комфортный': [0, 1, 1, 1, 1, 0],
        'Яркий':      [0, 0, 0, 1, 1, 1]
    },
    'Эксперт 4': {
        'Тусклый':    [1, 1, 0, 0, 0, 0],
        'Комфортный': [0, 1, 1, 1, 0, 0],
        'Яркий':      [0, 0, 0, 0, 1, 1]
    },
    'Эксперт 5': {
        'Тусклый':    [1, 1, 1, 0, 0, 0],
        'Комфортный': [0, 0, 1, 1, 1, 0],
        'Яркий':      [0, 0, 0, 1, 1, 1]
    }
}

n_experts = len(experts)

# 1. Подсчет голосов (аналог "чисел над чертой" в табл. 2 методички)
votes = {term: np.zeros(len(ranges), dtype=int) for term in terms}
for exp_data in experts.values():
    for term in terms:
        votes[term] += np.array(exp_data[term])

# 2. Расчет степеней принадлежности μ (аналог "чисел под чертой")
# Формула: μ = (сумма голосов) / (кол-во экспертов)
mu = {term: votes[term] / n_experts for term in terms}

print("\n1. Количество голосов экспертов:")
df_votes = pd.DataFrame(votes, index=ranges).T
print(df_votes)

print("\n2. Степени принадлежности μ (итоговая функция принадлежности):")
df_mu = pd.DataFrame(mu, index=ranges).T
print(df_mu.round(2))

# 3. Построение графика функций принадлежности
plt.figure(figsize=(10, 6))
x = np.arange(len(ranges))
colors = {'Тусклый': '#1f77b4', 'Комфортный': '#ff7f0e', 'Яркий': '#2ca02c'}
markers = {'Тусклый': 'o', 'Комфортный': 's', 'Яркий': '^'}

for term in terms:
    plt.plot(x, mu[term], marker=markers[term], color=colors[term], 
             label=term, linewidth=2.5, markersize=9)

plt.title('Функции принадлежности термов "Освещенность рабочего места"', fontsize=14)
plt.xlabel('Диапазоны освещенности (люкс)', fontsize=12)
plt.ylabel('Степень принадлежности μ', fontsize=12)
plt.xticks(x, ranges, rotation=45)
plt.legend(fontsize=12)
plt.grid(True, linestyle='--', alpha=0.7)
plt.ylim(-0.05, 1.1)
plt.tight_layout()
plt.show()